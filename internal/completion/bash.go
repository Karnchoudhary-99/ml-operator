package completion

import (
	"fmt"
	"strings"
)

// bashScript renders the bash completion for mlop.
//
// Behaviour: the first word completes command names; after a command,
// flags complete from that command's flag list, -f/-d complete files,
// and a deployment-name position completes from
// `mlop __complete-names` (passing --state through when the user gave
// one). `rollout` completes its `status` subcommand first, then a
// name; `completion` completes the shell names. A name already typed
// is not completed again.
func bashScript() string {
	var b strings.Builder
	b.WriteString(`# bash completion for mlop.
# Generated by ` + "`mlop completion bash`" + `; do not edit by hand.
# Install it with:
#   mlop completion bash | sudo tee /etc/bash_completion.d/mlop
# or source it for one shell:
#   source <(mlop completion bash)

_mlop() {
    local cur prev cmd sub state i w
    COMPREPLY=()
    cur="${COMP_WORDS[COMP_CWORD]}"
    prev="${COMP_WORDS[COMP_CWORD-1]}"

    # --state takes a file path.
    if [[ "$prev" == "--state" ]]; then
        COMPREPLY=( $(compgen -f -- "$cur") )
        return 0
    fi

    # The state file, if the user passed --state before the command.
    state=""
    for (( i=1; i<COMP_CWORD; i++ )); do
        if [[ "${COMP_WORDS[i]}" == "--state" && $((i+1)) -lt COMP_CWORD ]]; then
            state="${COMP_WORDS[i+1]}"
        fi
    done

    # Find the command: the first non-flag word, skipping --state's value.
    cmd=""
    for (( i=1; i<COMP_CWORD; i++ )); do
        w="${COMP_WORDS[i]}"
        if [[ "$w" == "--state" ]]; then
            i=$((i+1))
            continue
        fi
        if [[ "$w" == -* ]]; then
            continue
        fi
        cmd="$w"
        break
    done

    # No command yet: complete command names (or the global --state flag).
    if [[ -z "$cmd" ]]; then
        if [[ "$cur" == -* ]]; then
            COMPREPLY=( $(compgen -W "--state" -- "$cur") )
        else
            COMPREPLY=( $(compgen -W "`)
	b.WriteString(strings.Join(commandNames(), " "))
	b.WriteString(`" -- "$cur") )
        fi
        return 0
    fi

    # rollout completes its subcommand first, then a deployment name.
    if [[ "$cmd" == "rollout" ]]; then
        sub=""
        for (( i=1; i<COMP_CWORD; i++ )); do
            if [[ "${COMP_WORDS[i]}" == "rollout" && $((i+1)) -lt COMP_CWORD ]]; then
                sub="${COMP_WORDS[i+1]}"
                break
            fi
        done
        if [[ -z "$sub" ]]; then
            COMPREPLY=( $(compgen -W "status" -- "$cur") )
            return 0
        fi
        cmd="rollout status"
    fi

    # completion completes the shell names.
    if [[ "$cmd" == "completion" ]]; then
        COMPREPLY=( $(compgen -W "bash zsh fish" -- "$cur") )
        return 0
    fi

    # A value flag was just typed: -f/-d take files, the rest take
    # values mlop cannot complete (counts, durations, names).
    case "$prev" in
        -f|-d)
            COMPREPLY=( $(compgen -f -- "$cur") )
            return 0
            ;;`)
	b.WriteString("\n")
	for _, f := range []string{"--tail", "--replicas", "--interval", "--timeout", "--namespace", "--image"} {
		fmt.Fprintf(&b, "        %s)\n            return 0\n            ;;\n", f)
	}
	b.WriteString(`    esac

    # Flags for this command.
    if [[ "$cur" == -* ]]; then
        case "$cmd" in
`)
	for _, c := range Commands() {
		if len(c.Flags) == 0 {
			continue
		}
		fmt.Fprintf(&b, "            %s)\n                COMPREPLY=( $(compgen -W %q -- \"$cur\") )\n                ;;\n", c.Name, strings.Join(c.Flags, " "))
	}
	b.WriteString(`        esac
        return 0
    fi

    # A deployment name is already typed: nothing more to complete.
    # (Counts positionals after the command, skipping flag values.)
    local seen=0
    local after_cmd=0
    for (( i=1; i<COMP_CWORD; i++ )); do
        w="${COMP_WORDS[i]}"
        if [[ "$after_cmd" -eq 0 ]]; then
            if [[ "$w" == "$cmd" || ( "$cmd" == "rollout status" && "$w" == "status" ) ]]; then
                after_cmd=1
            fi
            continue
        fi
        case "$w" in
`)
	for _, f := range valueFlags() {
		fmt.Fprintf(&b, "            %s) i=$((i+1)) ;;\n", f)
	}
	b.WriteString(`            --state) i=$((i+1)) ;;
            -*) ;;
            *) seen=$((seen+1)) ;;
        esac
    done
    if [[ "$cmd" == "rollout status" && "$seen" -ge 1 ]]; then
        return 0
    fi
    if [[ "$cmd" != "rollout status" && "$seen" -ge 1 ]]; then
        return 0
    fi

    # Positional argument for this command.
    case "$cmd" in
        apply)
            # apply takes no positional; everything is -f/-d.
            return 0
            ;;
        backup|restore)
            COMPREPLY=( $(compgen -f -- "$cur") )
            return 0
            ;;
        crd|install|version|help)
            return 0
            ;;
        *)
            # Deployment names, from the same state file this shell uses.
            if [[ -n "$state" ]]; then
                COMPREPLY=( $(compgen -W "$(mlop --state "$state" __complete-names 2>/dev/null)" -- "$cur") )
            else
                COMPREPLY=( $(compgen -W "$(mlop __complete-names 2>/dev/null)" -- "$cur") )
            fi
            return 0
            ;;
    esac
}
complete -F _mlop mlop
`)
	return b.String()
}
