package completion

import (
	"fmt"
	"strings"
)

// fishScript renders the fish completion for mlop.
//
// Fish completions are declarative `complete` lines: one per command
// (shown while no subcommand is typed), one per flag (shown once its
// command is seen), and name lines that call
// `mlop __complete-names` for the commands that take a deployment.
// `rollout` gets a subcommand line for `status` and a name line that
// only fires once `status` is seen. Backup/restore complete files:
// their lines carry no -a, so fish falls back to file completion.
func fishScript() string {
	var b strings.Builder
	b.WriteString(`# fish completion for mlop.
# Generated by ` + "`mlop completion fish`" + `; do not edit by hand.
# Install it with:
#   mlop completion fish > ~/.config/fish/completions/mlop.fish

# The global --state flag takes a file path, wherever it appears.
complete -c mlop -f -l state -d 'path to the mlop state file' -r

`)
	// Commands, while no subcommand is typed yet.
	for _, c := range Commands() {
		fmt.Fprintf(&b, "complete -c mlop -f -n '__fish_use_subcommand' -a '%s' -d '%s'\n",
			c.Name, fishQuote(c.Description))
	}
	b.WriteString("\n")
	// Flags per command.
	for _, c := range Commands() {
		for _, f := range c.Flags {
			fmt.Fprintf(&b, "complete -c mlop -f -n '__fish_seen_subcommand_from %s' %s\n",
				c.Name, fishFlagSpec(f))
		}
	}
	b.WriteString("\n")
	// Deployment names for name-taking commands.
	for _, c := range nameCommands() {
		if c.Name == "rollout" {
			continue
		}
		fmt.Fprintf(&b, "complete -c mlop -f -n '__fish_seen_subcommand_from %s' -a '(mlop __complete-names)' -d 'deployment'\n", c.Name)
	}
	// rollout: subcommand first, then names once status is seen.
	b.WriteString("complete -c mlop -f -n '__fish_seen_subcommand_from rollout; and not __fish_seen_subcommand_from status' -a 'status' -d 'show rollout progress'\n")
	b.WriteString("complete -c mlop -f -n '__fish_seen_subcommand_from rollout; and __fish_seen_subcommand_from status' -a '(mlop __complete-names)' -d 'deployment'\n")
	// completion: the shell names.
	b.WriteString("complete -c mlop -f -n '__fish_seen_subcommand_from completion' -a 'bash zsh fish' -d 'shell'\n")
	// backup/restore take a file as their positional argument.
	for _, c := range Commands() {
		if !c.TakesFile {
			continue
		}
		fmt.Fprintf(&b, "complete -c mlop -n '__fish_seen_subcommand_from %s' -d 'backup file'\n", c.Name)
	}
	return b.String()
}

// fishFlagSpec renders one flag as fish complete arguments. Short
// flags get -s, long flags -l; value flags get -r so fish completes
// a value for them (files by default).
func fishFlagSpec(f string) string {
	if strings.HasPrefix(f, "--") {
		name := strings.TrimLeft(f, "-")
		if isValueFlag(f) {
			return fmt.Sprintf("-l %s -d '%s' -r", name, name)
		}
		return fmt.Sprintf("-l %s -d '%s'", name, name)
	}
	name := strings.TrimLeft(f, "-")
	if isValueFlag(f) {
		return fmt.Sprintf("-s %s -d '%s' -r", name, flagDescription(f))
	}
	return fmt.Sprintf("-s %s -d '%s'", name, flagDescription(f))
}

// flagDescription is the short help fish shows for a flag.
func flagDescription(f string) string {
	switch f {
	case "-f":
		return "manifest file"
	case "-d":
		return "directory of manifests"
	case "--dry-run":
		return "validate only"
	case "--json":
		return "print as JSON"
	case "--strict":
		return "treat warnings as errors"
	case "--tail":
		return "show at most N entries"
	case "--replicas":
		return "how many pods pass the readiness gate"
	case "--canary":
		return "target the canary Deployment"
	case "--green":
		return "target the green Deployment"
	case "--loading":
		return "report that the model is still loading"
	case "--fail":
		return "report that the model failed to load"
	case "--interval":
		return "how often to re-check"
	case "--timeout":
		return "give up after this long"
	case "--all":
		return "watch every deployment"
	case "--force":
		return "overwrite an existing file"
	case "--namespace":
		return "operator namespace"
	case "--image":
		return "operator container image"
	default:
		return strings.TrimLeft(f, "-")
	}
}

// isValueFlag reports whether a flag takes a value.
func isValueFlag(f string) bool {
	for _, v := range valueFlags() {
		if v == f {
			return true
		}
	}
	return false
}

// fishQuote escapes a description for a single-quoted fish string.
func fishQuote(s string) string {
	return strings.ReplaceAll(s, "'", `\'`)
}
